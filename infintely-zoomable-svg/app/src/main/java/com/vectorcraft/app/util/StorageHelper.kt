package com.vectorcraft.app.util

import android.content.ContentValues
import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Build
import android.os.Environment
import android.provider.MediaStore
import android.util.Log
import android.widget.Toast
import androidx.core.content.FileProvider
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object StorageHelper {
    private const val TAG = "StorageHelper"

    /**
     * Writes SVG export directly to the public Downloads folder using Scoped Storage (MediaStore).
     * No runtime storage permissions required on Android 10+ (API 29+).
     */
    fun saveSvgToDownloads(context: Context, svgContent: String, baseName: String = "vectorcraft"): Uri? {
        val timestamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US).format(Date())
        val fileName = "${baseName}_$timestamp.svg"
        val mimeType = "image/svg+xml"

        return try {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                val contentValues = ContentValues().apply {
                    put(MediaStore.MediaColumns.DISPLAY_NAME, fileName)
                    put(MediaStore.MediaColumns.MIME_TYPE, mimeType)
                    put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS + "/VectorCraft")
                    put(MediaStore.MediaColumns.IS_PENDING, 1)
                }

                val resolver = context.contentResolver
                val uri = resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, contentValues)

                if (uri != null) {
                    resolver.openOutputStream(uri)?.use { outputStream ->
                        outputStream.write(svgContent.toByteArray(Charsets.UTF_8))
                    }

                    contentValues.clear()
                    contentValues.put(MediaStore.MediaColumns.IS_PENDING, 0)
                    resolver.update(uri, contentValues, null, null)
                    Log.i(TAG, "SVG successfully written to Downloads via MediaStore: $uri")
                    uri
                } else {
                    null
                }
            } else {
                // Fallback for API < 29
                val downloadsDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS)
                val targetDir = File(downloadsDir, "VectorCraft")
                if (!targetDir.exists()) targetDir.mkdirs()
                val targetFile = File(targetDir, fileName)
                FileOutputStream(targetFile).use { it.write(svgContent.toByteArray(Charsets.UTF_8)) }
                Uri.fromFile(targetFile)
            }
        } catch (e: Exception) {
            Log.e(TAG, "Failed to save SVG to Downloads", e)
            null
        }
    }

    /**
     * Shares SVG via Android's native ACTION_SEND Share Sheet using FileProvider.
     */
    fun shareSvg(context: Context, svgContent: String, baseName: String = "vectorcraft") {
        try {
            val exportDir = File(context.cacheDir, "exports")
            if (!exportDir.exists()) exportDir.mkdirs()

            val tempFile = File(exportDir, "${baseName}_shared.svg")
            FileOutputStream(tempFile).use {
                it.write(svgContent.toByteArray(Charsets.UTF_8))
            }

            val contentUri: Uri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                tempFile
            )

            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "image/svg+xml"
                putExtra(Intent.EXTRA_STREAM, contentUri)
                putExtra(Intent.EXTRA_SUBJECT, "Exported SVG - VectorCraft")
                putExtra(Intent.EXTRA_TEXT, "Exported vector graphic generated by VectorCraft on-device Rust engine.")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }

            val chooser = Intent.createChooser(shareIntent, "Share Vectorized SVG")
            chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            context.startActivity(chooser)
        } catch (e: Exception) {
            Log.e(TAG, "Failed to share SVG", e)
            Toast.makeText(context, "Failed to share SVG: ${e.message}", Toast.LENGTH_SHORT).show()
        }
    }
}
